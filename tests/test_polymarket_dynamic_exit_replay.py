# --- Deterministic, realistic BTC tick generation -----------------------------

def _ticks_from_minute_closes(
    minute_closes: list[float], *, ticks_per_minute: int = 4, jitter: float = 0.02, seed: int,
) -> tuple[list[tuple[float, datetime]], datetime]:
    """Realistic multi-tick-per-minute price action: each minute's
    intended close gets `ticks_per_minute` samples, each jittered by a
    seeded PRNG -- same seed always produces the exact same ticks."""
    rng = random.Random(seed)
    ticks: list[tuple[float, datetime]] = []
    t = _BASE_T
    for close in minute_closes:
        for _ in range(ticks_per_minute):
            ticks.append((close + rng.uniform(-jitter, jitter), t))
            t += timedelta(seconds=60 // ticks_per_minute)
    return ticks, t


def _drifting_noisy_closes(*, drift: float, noise: float, seed: int, n: int = 45) -> list[float]:
    """A seeded random walk: closes[i] = closes[i-1] + drift + U(-noise,
    noise). Used to reach STABLE/WEAKENING/REVERSING deterministically
    -- see the per-state comments below for the exact search result."""
    r = random.Random(seed)
    closes = [100.0]
    for _ in range(1, n):
        closes.append(closes[-1] + drift + r.uniform(-noise, noise))
    return closes


def _strengthening_closes(n: int = 45) -> list[float]:
    """A mild, healthy uptrend with real pullbacks -- NOT a straight
    line (which reads as overbought/exhausted, see
    test_polymarket_btc_intelligence.py's own note on this). Verified:
    STRENGTHENING, weakening=0, strengthening=2
    ('trend_intact', 'rsi_healthy_range')."""
    return [100.0 + i * 0.05 + 1.0 * math.sin(i / 2.0) for i in range(n)]


