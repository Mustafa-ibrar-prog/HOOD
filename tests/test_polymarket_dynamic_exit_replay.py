def _feed(store: BtcPriceHistoryStore, minute_closes: list[float], *, seed: int) -> datetime:
    ticks, end_t = _ticks_from_minute_closes(minute_closes, seed=seed)
    for price, at in ticks:
        store.record_quote(price, at=at)
    return end_t


