# --- 8. One-tick deterioration -> no premature exit ---------------------------

def test_scenario_8_single_tick_deterioration_does_not_trigger_an_exit(tmp_path):
    """A single bad bar inserted at the very end of an otherwise
    healthy uptrend can at most nudge the state from STRENGTHENING to
    STABLE (never straight to WEAKENING/REVERSING with enough
    signals) -- see evaluate_momentum's own "a single soft signal is
    never enough" guarantee. Evaluated BELOW target so neither the
    early-exit-on-weakening path nor the at-target STABLE-exits path
    can fire; the position must simply hold."""
    base_closes = _strengthening_closes()
    closes_with_one_bad_tick = list(base_closes)
    closes_with_one_bad_tick[-1] = closes_with_one_bad_tick[-2] - 4.0  # one sharp, isolated drop

    harness = _paper_harness(tmp_path)
    position = _position()
    harness["position_store"].add_if_absent(position)
    end_t = _feed(harness["btc_price_store"], closes_with_one_bad_tick, seed=5)
    harness["client"].set_order_book("tok-1", _book(0.378))  # +5%, below target

    bars, book, assessment = _assess(harness["btc_price_store"], harness["client"], position, now=end_t + timedelta(seconds=5))
    # One isolated bad tick never flips STRENGTHENING straight into
    # WEAKENING/REVERSING -- at most a cautious downgrade to STABLE.
    assert assessment.state in (MomentumState.STRENGTHENING, MomentumState.STABLE)

    submitted = check_and_execute_dynamic_exits(**harness, now=end_t + timedelta(seconds=5))
    assert submitted == 0
    assert harness["position_store"].load()[0].filled_shares == 5.0


