def _assess(btc_price_store: BtcPriceHistoryStore, client: _FakeClient, position: OpenPosition, *, now: datetime):
    """Builds the REAL BtcMarketAssessment exactly as
    check_and_execute_dynamic_exits() does internally -- used by tests
    that call evaluate_dynamic_exit() directly (to assert on the
    decision object) rather than only through the full
    check_and_execute_dynamic_exits() orchestrator."""
